#!/usr/bin/env python3
"""Builds src/apps_local/clock/ClockDigits.h: the ten numerals of Inter Display
in two weights, as runs of ink a row at a time, for the clock's TAMBOR face.

    python3 tools_local/clock/make_digits.py /usr/share/fonts/opentype/inter

Inter is under the SIL Open Font License; only these twenty shapes are taken.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

HEIGHT = 212  # the numerals' own height on the panel, in pixels
WEIGHTS = (("Bold", "InterDisplay-Bold.otf"), ("Light", "InterDisplay-Light.otf"))


def glyph(font, ch, cell_w, top, bottom):
    im = Image.new("L", (cell_w, bottom - top), 0)
    box = font.getbbox(ch)
    x = (cell_w - (box[2] - box[0])) // 2 - box[0]
    ImageDraw.Draw(im).text((x, -top), ch, font=font, fill=255)
    rows = []
    for y in range(im.height):
        runs, start = [], None
        for xx in range(cell_w + 1):
            on = xx < cell_w and im.getpixel((xx, y)) >= 128
            if on and start is None:
                start = xx
            elif not on and start is not None:
                runs += [start, xx - start]
                start = None
        rows.append(runs)
    return rows


def main():
    folder = sys.argv[1]
    out = ["#pragma once", "",
           "// Generated by tools_local/clock/make_digits.py from Inter Display (SIL OFL). Do not edit.",
           "// Each numeral is a list of rows; a row is a count of runs, then start and length of each.",
           "", "#include <cstdint>", "", "namespace clockdigits {", "", "constexpr int kHeight = %d;" % HEIGHT, ""]
    for name, file in WEIGHTS:
        size = 100
        font = ImageFont.truetype("%s/%s" % (folder, file), size)
        box = font.getbbox("0")
        size = int(round(size * HEIGHT / (box[3] - box[1])))
        font = ImageFont.truetype("%s/%s" % (folder, file), size)
        boxes = [font.getbbox(str(d)) for d in range(10)]
        top = min(b[1] for b in boxes)
        bottom = top + HEIGHT
        cell_w = max(b[2] - b[0] for b in boxes) + 2
        data, offsets = [], []
        for d in range(10):
            offsets.append(len(data))
            for runs in glyph(font, str(d), cell_w, top, bottom):
                data.append(len(runs) // 2)
                data += runs
        out.append("constexpr int k%sWidth = %d;" % (name, cell_w))
        out.append("constexpr uint16_t k%sOffsets[10] = {%s};" % (name, ", ".join(map(str, offsets))))
        out.append("constexpr uint8_t k%sRuns[] = {" % name)
        assert max(data) < 256, max(data)
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(map(str, data[i:i + 24])) + ",")
        out.append("};")
        out.append("")
        print(name, "cell", cell_w, "bytes", len(data))
    out += ["}  // namespace clockdigits", ""]
    with open("src/apps_local/clock/ClockDigits.h", "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
