#!/usr/bin/env python3
"""Builds src/apps_local/clock/ClockType.h: the letters and numerals RELOJ's ten
faces are set in, each at the sizes a face uses, as runs of ink a row at a time.

    python3 tools_local/clock/make_type.py <folder with the .ttf files>

The folder holds these files from github.com/google/fonts (all under the SIL
Open Font License), saved under these names: InstrumentSerif-Regular.ttf,
InstrumentSerif-Italic.ttf, GeistMono.ttf, Doto.ttf, BigShoulders.ttf,
Bricolage.ttf, Fraunces.ttf, Fraunces-Italic.ttf, MartianMono.ttf,
Unbounded.ttf, Jersey10.ttf, Syne.ttf, Geist.ttf. Only the glyphs a face draws
are taken.
"""
