def load(folder, file, axes, size):
    font = ImageFont.truetype("%s/%s" % (folder, file), size)
    if axes:
        names = [a["name"].decode() for a in font.get_variation_axes()]
        defaults = {a["name"].decode(): a["default"] for a in font.get_variation_axes()}
        defaults.update(axes)
        font.set_variation_by_axes([defaults[n] for n in names])
    return font


def main():
    folder = sys.argv[1]
    out = ["#pragma once", "",
           "// Generated by tools_local/clock/make_type.py from Google Fonts files (SIL OFL). Do not edit.",
           "// A glyph is rows of ink from its top; a row is a count of runs, then start and length of each.",
           "", "#include <cstdint>", "", "namespace clocktype {", "",
           "struct Glyph {", "  uint16_t codepoint;", "  int16_t advance;", "  int16_t left;  // of the ink, from the pen",
           "  int16_t top;   // of the ink, above the baseline", "  uint16_t rows;", "  uint32_t offset;", "};", "",
           "struct Font {", "  const Glyph* glyphs;", "  uint16_t count;", "  const uint8_t* runs;",
           "  int16_t capTop;  // how far a numeral or a capital stands above the baseline", "};", ""]
    total = 0
    for name, file, axes, size, chars in FONTS:
        font = load(folder, file, axes, size)
        data, glyphs = [], []
        for ch in sorted(set(chars)):
            advance = int(round(font.getlength(ch)))
            box = font.getbbox(ch, anchor="ls")  # relative to the pen on the baseline
            w, h = box[2] - box[0], box[3] - box[1]
            rows = []
            if w > 0 and h > 0:
                im = Image.new("L", (w + 2, h + 2), 0)
                ImageDraw.Draw(im).text((-box[0] + 1, -box[1] + 1), ch, font=font, fill=255, anchor="ls")
                px = im.load()
                for y in range(1, h + 1):
                    runs, start = [], None
                    for x in range(1, w + 3):
                        on = x <= w and px[x, y] >= 128
                        if on and start is None:
                            start = x - 1
                        elif not on and start is not None:
                            runs += [start, x - 1 - start]
                            start = None
                    rows.append(runs)
                while rows and not rows[-1]:
                    rows.pop()
            offset = len(data)
            for runs in rows:
                data.append(len(runs) // 2)
                data += runs
            glyphs.append((ord(ch), advance, box[0], -box[1], len(rows), offset))
        assert not data or max(data) < 256, (name, max(data))
        ref = "0" if "0" in chars else ("H" if "H" in chars else "x")
        cap = -font.getbbox(ref, anchor="ls")[1]
        out.append("inline constexpr uint8_t k%sRuns[] = {" % name)
        for i in range(0, len(data), 32):
            out.append("    " + ", ".join(map(str, data[i:i + 32])) + ",")
        out.append("};")
        out.append("inline constexpr Glyph k%sGlyphs[] = {" % name)
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append("inline constexpr Font k%s = {k%sGlyphs, %d, k%sRuns, %d};" % (name, name, len(glyphs), name, cap))
        out.append("")
        total += len(data) + len(glyphs) * 16
    out += ["}  // namespace clocktype", ""]
    with open("src/apps_local/clock/ClockType.h", "w") as f:
        f.write("\n".join(out))
    print("%d faces of type, about %d bytes" % (len(FONTS), total))


if __name__ == "__main__":
    main()
